CHANNEL_PLACEHOLDER_RE = re.compile(r"\{([a-zA-Z0-9_-]+)\}")
CHANNEL_MENTION_RE = re.compile(r"<#(\d+)>")


def _channel_alias(name: str) -> str:
    """Normalize decorated Discord channel names to a stable admin placeholder."""
    name = name.lower().strip()
    # GamerHQ channels can be decorated, e.g. "🎮・choose-your-games".
    # Keep only ASCII letters/numbers/hyphens so {choose-your-games} stays stable.
    name = re.sub(r"[^a-z0-9_-]+", "", name)
    return name.strip("-_")


def resolve_channel_placeholders(guild: discord.Guild, text: str) -> str:
    """Turn {channel-name} placeholders into real Discord channel mentions."""
    by_alias: dict[str, list[discord.abc.GuildChannel]] = {}
    for channel in guild.channels:
        if isinstance(channel, (discord.TextChannel, discord.VoiceChannel, discord.ForumChannel)):
            alias = _channel_alias(channel.name)
            if alias:
                by_alias.setdefault(alias, []).append(channel)

    def replace(match: re.Match) -> str:
        alias = _channel_alias(match.group(1))
        matches = by_alias.get(alias, [])
        if len(matches) != 1:
            return match.group(0)
        return matches[0].mention

    return CHANNEL_PLACEHOLDER_RE.sub(replace, text)


def restore_channel_placeholders(guild: discord.Guild, text: str) -> str:
    """Show stored channel mentions as readable {channel-name} placeholders in the editor."""
    def replace(match: re.Match) -> str:
        channel = guild.get_channel(int(match.group(1)))
        if channel is None:
            return match.group(0)
        alias = _channel_alias(channel.name)
        return "{" + (alias or channel.name) + "}"

    return CHANNEL_MENTION_RE.sub(replace, text)


