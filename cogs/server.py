async def refresh_lfg_guide_message(guild: discord.Guild):
    """Refresh the official LFG help message without touching member event posts."""
    from services.lfg_service import find_lfg_channel
    channel = find_lfg_channel(guild)
    if not isinstance(channel, discord.TextChannel):
        return None
    return await upsert_fixed_message(
        channel,
        setting_key=setting_key_for(channel),
        content=resolve_channel_placeholders(guild, default_copy_for(channel)),
        pin=True,
        view=managed_channel_view(channel),
    )


class ConfirmPinnedMessageView(discord.ui.View):
    def __init__(self, *, channel: discord.TextChannel, message: str, admin_id: int):
        super().__init__(timeout=180)
        self.channel = channel
        self.message = message
        self.rendered_message = resolve_channel_placeholders(channel.guild, message)
        self.admin_id = admin_id
        self.finished = False

    async def interaction_check(self, interaction: discord.Interaction) -> bool:
        if interaction.user.id != self.admin_id:
            await interaction.response.send_message("❌ Only the admin who opened this preview can use these buttons.", ephemeral=True)
            return False
        return True

    @discord.ui.button(label="Edit", emoji="✏️", style=discord.ButtonStyle.secondary, row=1)
    async def edit(self, interaction: discord.Interaction, button: discord.ui.Button):
        await interaction.response.send_modal(
            EditPinnedMessageModal(channel=self.channel, current_message=self.message, admin_id=self.admin_id)
        )

    @discord.ui.button(label="Save & Pin", emoji="✅", style=discord.ButtonStyle.success, row=1)
    async def confirm(self, interaction: discord.Interaction, button: discord.ui.Button):
        from database import db
        from services.onboarding_service import key
        if (_channel_alias(self.channel.name) in {'introductions', 'newbies', 'bot-commands', 'community-commands', 'guide', 'suggestions', 'support-gamerhq', 'need-support', 'germany-services', 'gaming-deals', 'ai-tools'}
            or str(db.get_setting(key(self.channel.guild, 'newbies'))) == str(self.channel.id)):
            return await interaction.response.send_message('This channel does not use the free-text pinned guide editor.', ephemeral=True)
        if self.finished:
            await interaction.response.send_message("This update has already been handled.", ephemeral=True)
            return
        self.finished = True
        for item in self.children:
            item.disabled = True
        await interaction.response.edit_message(
            content=f"⏳ Saving the managed pinned message…\n\n{self.rendered_message}",
            view=self,
        )
        try:
            # The Choose Your Roles hub owns a fixed set of GamerHQ base roles.
            # Sync them during admin setup so normal members never need role-management permissions.
            if _channel_alias(self.channel.name) == "choose-your-roles":
                from services.role_service import ensure_base_roles
                await ensure_base_roles(self.channel.guild)

            managed_message = await upsert_fixed_message(
                self.channel,
                setting_key=setting_key_for(self.channel),
                content=self.rendered_message,
                pin=True,
                view=managed_channel_view(self.channel),
            )
        except discord.Forbidden:
            await interaction.followup.send(
                "❌ I could not create the GamerHQ roles. Give the GamerHQ Bot **Manage Roles** permission and keep its role above the roles it manages.",
                ephemeral=True,
            )
            return
        except (ServerMessageError, discord.HTTPException) as exc:
            await interaction.followup.send(f"❌ Could not save the managed pinned message.\n`{exc}`", ephemeral=True)
            return
        await interaction.edit_original_response(
            content=f"✅ Managed message saved and pinned in {self.channel.mention}.\nMessage ID: `{managed_message.id}`",
            view=None,
        )
        self.stop()

    @discord.ui.button(label="Cancel", emoji="✖️", style=discord.ButtonStyle.danger, row=1)
    async def cancel(self, interaction: discord.Interaction, button: discord.ui.Button):
        self.finished = True
        await interaction.response.edit_message(content="✖️ Cancelled. Nothing was changed.", view=None)
        self.stop()


class EditPinnedMessageModal(discord.ui.Modal, title="Edit Pinned Message"):
    def __init__(self, *, channel: discord.TextChannel, current_message: str, admin_id: int):
        super().__init__(timeout=300)
        self.channel = channel
        self.admin_id = admin_id
        self.message_body = discord.ui.TextInput(
            label="Message (Discord Markdown + {channel-name})",
            default=current_message,
            style=discord.TextStyle.paragraph,
            max_length=2000,
            required=True,
        )
        self.add_item(self.message_body)

    async def on_submit(self, interaction: discord.Interaction):
        message = str(self.message_body.value).strip()
        rendered_message = resolve_channel_placeholders(self.channel.guild, message)
        unresolved = sorted(set(CHANNEL_PLACEHOLDER_RE.findall(rendered_message)))
        warning = ""
        if unresolved:
            warning = "\n\n⚠️ Unresolved channel link(s): " + ", ".join(f"`{{{name}}}`" for name in unresolved)

        await interaction.response.send_message(
            f"**📌 Pinned Message Preview — {self.channel.mention}**\n"
            f"Check the formatting below. Nothing has been changed yet.{warning}\n\n"
            f"{rendered_message}",
            view=ConfirmPinnedMessageView(channel=self.channel, message=message, admin_id=self.admin_id),
            ephemeral=True,
        )


async def open_channel_editor(interaction: discord.Interaction, channel: discord.TextChannel):
    from services.ticket_service import list_tickets
    if any(item['channel_id']==channel.id for item in list_tickets(interaction.guild.id)):
        return await interaction.response.send_message('ℹ️ Ticket messages are maintained by the ticket controls.',ephemeral=True)
    if _channel_alias(channel.name) in {'introductions', 'newbies', 'bot-commands', 'community-commands', 'guide', 'suggestions', 'support-gamerhq', 'need-support', 'germany-services', 'gaming-deals', 'ai-tools'}:
        return await interaction.response.send_message('Introductions/newbies have no managed guide. The bot command guide is generated by /server setup.', ephemeral=True)
    # choose-your-games is generated by the game system and must not be overwritten as free text.
    if _channel_alias(channel.name) == "choose-your-games":
        await interaction.response.send_message(
            "🎮 **Choose Your Games is bot-generated.**\n"
            "Its pinned overview will use the same management screen, but its game list must stay generated from the catalog. "
            "We will add its protected formatting editor next.",
            ephemeral=True,
        )
        return

    current_message = default_copy_for(channel)
    try:
        managed_message = await get_fixed_message(channel, setting_key=setting_key_for(channel))
    except ServerMessageError as exc:
        await interaction.response.send_message(f"❌ Could not read the managed message.\n`{exc}`", ephemeral=True)
        return

    if managed_message:
        if managed_message.content:
            current_message = restore_channel_placeholders(channel.guild, managed_message.content)
        elif managed_message.embeds:
            # One-time migration path from the old embed-based managed messages.
            embed = managed_message.embeds[0]
            title = embed.title or ""
            body = embed.description or ""
            combined = f"# {title}\n\n{body}" if title else body
            current_message = restore_channel_placeholders(channel.guild, combined)

    await interaction.response.send_modal(
        EditPinnedMessageModal(channel=channel, current_message=current_message, admin_id=interaction.user.id)
    )


