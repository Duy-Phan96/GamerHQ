class RoleCleanupSelect(discord.ui.Select):
    def __init__(self, *, candidates, selected_ids: set[int]):
        options = []
        for role, reason in candidates[:25]:
            count = len(role.members)
            description = f"{count} member{'s' if count != 1 else ''} • {reason}"[:100]
            options.append(
                discord.SelectOption(
                    label=role.name[:100],
                    value=str(role.id),
                    description=description,
                    default=role.id in selected_ids,
                )
            )
        super().__init__(
            placeholder="Select roles to remove",
            min_values=0,
            max_values=len(options),
            options=options,
            row=0,
        )

    async def callback(self, interaction: discord.Interaction):
        view = self.view
        view.selected_ids = {int(value) for value in self.values}
        await interaction.response.edit_message(
            content=view.render_content(),
            view=RoleCleanupSelectView(
                guild=view.guild,
                admin_id=view.admin_id,
                candidates=view.candidates,
                selected_ids=view.selected_ids,
            ),
        )


class RoleCleanupSelectView(discord.ui.View):
    def __init__(self, *, guild: discord.Guild, admin_id: int, candidates, selected_ids: set[int] | None = None):
        super().__init__(timeout=180)
        self.guild = guild
        self.admin_id = admin_id
        self.candidates = candidates[:25]
        self.selected_ids = set(selected_ids or set())
        self.add_item(RoleCleanupSelect(candidates=self.candidates, selected_ids=self.selected_ids))

    async def interaction_check(self, interaction: discord.Interaction) -> bool:
        if interaction.user.id != self.admin_id:
            await interaction.response.send_message("❌ This cleanup belongs to another admin session.", ephemeral=True)
            return False
        return True

    def render_content(self) -> str:
        selected = [role for role, _ in self.candidates if role.id in self.selected_ids]
        affected = len({member.id for role in selected for member in role.members})
        lines = [
            "**🧹 Role Cleanup**",
            "Select exactly which roles you want to remove.",
            "Nothing is deleted until the final confirmation.",
            "",
            f"Selected: **{len(selected)}** role(s) • **{affected}** unique member(s) affected",
        ]
        if len(self.candidates) >= 25:
            lines.append("ℹ️ Discord shows up to 25 cleanup candidates at once.")
        return "\n".join(lines)

