async def refresh_lfg_guide_message(guild: discord.Guild):
    """Refresh the official LFG help message without touching member event posts."""
    from services.lfg_service import find_lfg_channel
    channel = find_lfg_channel(guild)
    if not isinstance(channel, discord.TextChannel):
        return None
    return await upsert_fixed_message(
        channel,
        setting_key=setting_key_for(channel),
        content=resolve_channel_placeholders(guild, default_copy_for(channel)),
        pin=True,
        view=managed_channel_view(channel),
    )


class RoleCleanupSelect(discord.ui.Select):
    def __init__(self, *, candidates, selected_ids: set[int]):
        options = []
        for role, reason in candidates[:25]:
            count = len(role.members)
            description = f"{count} member{'s' if count != 1 else ''} • {reason}"[:100]
            options.append(
                discord.SelectOption(
                    label=role.name[:100],
                    value=str(role.id),
                    description=description,
                    default=role.id in selected_ids,
                )
            )
        super().__init__(
            placeholder="Select roles to remove",
            min_values=0,
            max_values=len(options),
            options=options,
            row=0,
        )

    async def callback(self, interaction: discord.Interaction):
        view = self.view
        view.selected_ids = {int(value) for value in self.values}
        await interaction.response.edit_message(
            content=view.render_content(),
            view=RoleCleanupSelectView(
                guild=view.guild,
                admin_id=view.admin_id,
                candidates=view.candidates,
                selected_ids=view.selected_ids,
            ),
        )


class RoleCleanupSelectView(discord.ui.View):
    def __init__(self, *, guild: discord.Guild, admin_id: int, candidates, selected_ids: set[int] | None = None):
        super().__init__(timeout=180)
        self.guild = guild
        self.admin_id = admin_id
        self.candidates = candidates[:25]
        self.selected_ids = set(selected_ids or set())
        self.add_item(RoleCleanupSelect(candidates=self.candidates, selected_ids=self.selected_ids))

    async def interaction_check(self, interaction: discord.Interaction) -> bool:
        if interaction.user.id != self.admin_id:
            await interaction.response.send_message("❌ This cleanup belongs to another admin session.", ephemeral=True)
            return False
        return True

    def render_content(self) -> str:
        selected = [role for role, _ in self.candidates if role.id in self.selected_ids]
        affected = len({member.id for role in selected for member in role.members})
        lines = [
            "**🧹 Role Cleanup**",
            "Select exactly which roles you want to remove.",
            "Nothing is deleted until the final confirmation.",
            "",
            f"Selected: **{len(selected)}** role(s) • **{affected}** unique member(s) affected",
        ]
        if len(self.candidates) >= 25:
            lines.append("ℹ️ Discord shows up to 25 cleanup candidates at once.")
        return "\n".join(lines)

    @discord.ui.button(label="Continue", emoji="➡️", style=discord.ButtonStyle.primary, row=1)
    async def continue_cleanup(self, interaction: discord.Interaction, button: discord.ui.Button):
        if not self.selected_ids:
            await interaction.response.send_message("ℹ️ Select at least one role first.", ephemeral=True)
            return
        selected = [(role, reason) for role, reason in self.candidates if role.id in self.selected_ids]
        await interaction.response.edit_message(
            content=render_cleanup_preview(selected),
            view=ConfirmRoleCleanupView(
                guild=self.guild,
                admin_id=self.admin_id,
                candidates=self.candidates,
                selected_ids=self.selected_ids,
            ),
        )

    @discord.ui.button(label="Back", emoji="⬅️", style=discord.ButtonStyle.secondary, row=1)
    async def back(self, interaction: discord.Interaction, button: discord.ui.Button):
        await interaction.response.edit_message(
            content="**⚙️ Manage GamerHQ Roles**\nSync required base roles, review the current setup or safely clean up old GamerHQ role duplicates.",
            view=RoleAdminView(guild=self.guild, admin_id=self.admin_id),
        )

    @discord.ui.button(label="Cancel", emoji="✖️", style=discord.ButtonStyle.danger, row=1)
    async def cancel(self, interaction: discord.Interaction, button: discord.ui.Button):
        await interaction.response.edit_message(content="✖️ Cleanup cancelled. Nothing was deleted.", view=None)
        self.stop()


def render_cleanup_preview(selected) -> str:
    unique_members = {member.id for role, _ in selected for member in role.members}
    lines = [
        "**⚠️ Cleanup Preview**",
        "The following roles will be permanently deleted:",
        "",
    ]
    for role, reason in selected:
        count = len(role.members)
        lines.append(f"• **{role.name}** — 👥 {count} member{'s' if count != 1 else ''}")
        lines.append(f"  ↳ {reason}")
    lines.extend([
        "",
        f"**{len(selected)} role(s)** selected • **{len(unique_members)} unique member(s)** affected",
        "Members using these roles will lose them.",
    ])
    return "\n".join(lines)


