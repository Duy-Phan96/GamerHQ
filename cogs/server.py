    async def refresh_default_managed_messages(self, guild: discord.Guild):
        """Refresh fixed server copy that is owned by GamerHQ itself.

        Introductions used to be an embed. If the stored message id is missing,
        recover the existing bot-authored legacy/new introductions message first
        so startup edits it in place instead of posting a duplicate.
        """
        channel = guild.get_channel(INTRODUCTIONS_CHANNEL_ID) if INTRODUCTIONS_CHANNEL_ID else None
        if not isinstance(channel, discord.TextChannel):
            channel = next(
                (
                    ch for ch in guild.text_channels
                    if _channel_alias(ch.name) == "introductions"
                ),
                None,
            )
        if channel is None:
            return None

        setting_key = setting_key_for(channel)
        managed = await get_fixed_message(channel, setting_key=setting_key)

        if managed is None:
            bot_user = guild.me
            if bot_user is not None:
                # Prefer pinned messages, because the legacy introduction was
                # intended to be a fixed server message.
                candidates = []
                try:
                    candidates.extend(await channel.pins())
                except (discord.Forbidden, discord.HTTPException):
                    pass

                # Fall back to recent history if it is no longer pinned or the
                # old setting id was lost during a database/project migration.
                try:
                    async for message in channel.history(limit=100):
                        if all(message.id != item.id for item in candidates):
                            candidates.append(message)
                except (discord.Forbidden, discord.HTTPException):
                    pass

                for message in candidates:
                    if message.author.id != bot_user.id:
                        continue

                    content_match = "introduce yourself" in (message.content or "").lower()
                    embed_match = any(
                        "introduce yourself" in ((embed.title or "") + " " + (embed.description or "")).lower()
                        for embed in message.embeds
                    )
                    if content_match or embed_match:
                        db.set_setting(setting_key, message.id)
                        managed = message
                        break

        return await upsert_fixed_message(
            channel,
            setting_key=setting_key,
            content=resolve_channel_placeholders(guild, default_copy_for(channel)),
            pin=True,
            view=managed_channel_view(channel),
        )

