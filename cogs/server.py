async def refresh_future_community_messages(guild: discord.Guild):
    """Keep the V27 tournament/giveaway coming-soon pins current."""
    copies = {
        "tournaments": (
            "# 🏆 GamerHQ Tournaments\n\n"
            "Community tournaments are coming to GamerHQ!\n\n"
            "As the community grows, we'll start hosting tournaments across different games — "
            "compete, team up and play for the win. 🏆\n\n"
            "**More details coming as GamerHQ grows. 🚀**"
        ),
        "giveaways": (
            "# 🎁 GamerHQ Giveaways\n\n"
            "Giveaways are coming to GamerHQ!\n\n"
            "As our community grows, we'll introduce community giveaways, special events and rewards "
            "for GamerHQ members. 🎉\n\n"
            "**Stay tuned — more is coming. 🚀**"
        ),
    }
    results = []
    for alias, content in copies.items():
        channel = next((ch for ch in guild.text_channels if _channel_alias(ch.name) == alias), None)
        if not isinstance(channel, discord.TextChannel):
            continue
        message = await upsert_fixed_message(
            channel,
            setting_key=f"server_future_{alias}_message_id",
            content=content,
            pin=True,
            view=None,
        )
        results.append(message)
    return results
