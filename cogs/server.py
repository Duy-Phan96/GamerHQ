    def __init__(self, *, category: discord.CategoryChannel, admin_id: int):
        channels = [c for c in category.text_channels if c.permissions_for(category.guild.me).view_channel]
        options = [discord.SelectOption(label=c.name[:100], value=str(c.id)) for c in channels[:25]]
        super().__init__(placeholder=f"Select a channel in {category.name}", min_values=1, max_values=1, options=options)
        self.category = category
        self.admin_id = admin_id

    async def callback(self, interaction: discord.Interaction):
        if interaction.user.id != self.admin_id:
            await interaction.response.send_message("❌ This menu belongs to another admin session.", ephemeral=True)
            return
        channel = interaction.guild.get_channel(int(self.values[0])) if interaction.guild else None
        if not isinstance(channel, discord.TextChannel):
            await interaction.response.send_message("❌ That text channel could not be found.", ephemeral=True)
            return
        await open_channel_editor(interaction, channel)


